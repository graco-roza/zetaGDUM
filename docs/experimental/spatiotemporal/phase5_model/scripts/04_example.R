source("docs/experimental/spatiotemporal/phase5_model/scripts/common.R")
sim <- st5_simulate(seed=512,n=18,species=60,times=16,scenario="irregular")
records <- st5_missing(sim,.25,"network",seed=43)
p <- st5_input(records,incidence=sim$abundance>0,env=sim$env)
annual <- st5_support(p,"change",k=2,budget=64L)
attr <- st5_responses(p,annual,processes=TRUE,draws=8L)
response <- st5_extract(attr,"incidence")
fold <- st5_validate(p,response,"forward",blocks=4L)
if(!length(fold$folds)) stop("Example has no forward validation support.")
print(fold$scores[,c("fold","model","train","test","rmse")],row.names=FALSE)
print(head(st5_importance(fold)))
d <- fold$folds[[length(fold$folds)]]
pred <- st5_predict(.st5_refit(d),d$te,d$b)
stopifnot(max(abs(rowSums(pred$phi)-pred$change),na.rm=TRUE)<1e-10)
write_result(fold$scores,"example_forward_validation")
write_result(st5_eligibility(p,annual),"example_eligibility")
