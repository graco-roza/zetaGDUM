test_that("independent-pool products and numerical correction agree", {
  set.seed(180)
  n <- 35L
  truth <- matrix(rnorm(n * 3L), n)
  pools <- replicate(4L, truth + matrix(rnorm(n * 3L), n), simplify = FALSE)
  first <- scale(pools[[1L]], scale = FALSE)
  second <- scale(pools[[2L]], scale = FALSE)
  num <- crossprod(first - second) / (2 * (n - 1))
  cross <- (crossprod(first, second) + crossprod(second, first)) / (2 * (n - 1))
  pair <- ugdm_score_covariance(pools[1:2])
  expect_equal(pair$numerical, unname(num))
  expect_equal(pair$cross, unname(cross))
  expect_equal(pair$cross, pair$average - pair$numerical)
  all <- ugdm_score_covariance(pools, contrasts = c(1, -1, 0))
  all_pairs <- combn(4L, 2L, function(i) ugdm_score_covariance(pools[i])$cross,
                    simplify = FALSE)
  expect_equal(all$cross, Reduce("+", all_pairs) / length(all_pairs))
  expect_equal(all$pooled, cov(Reduce("+", pools) / length(pools)))
  expect_equal(all$contrasts$cross, matrix(drop(c(1, -1, 0) %*% all$cross %*% c(1, -1, 0))))
  expect_true(all(is.finite(all$numerical_se)))
})

test_that("score covariance regularisations report the spectrum and adjustment", {
  set.seed(522)
  A <- matrix(rnorm(100), 25L)
  B <- -A
  raw <- ugdm_score_covariance(list(A, B))
  expect_true(all(raw$spectrum < 0))
  psd <- ugdm_score_covariance(list(A, B), regularization = "psd")
  expect_equal(psd$adjusted_spectrum, rep(0, 4L))
  expect_gt(psd$adjustment, 0)
  eigen <- ugdm_score_covariance(list(A, B), regularization = "eigen", eigen_floor = .02)
  expect_equal(eigen$adjusted_spectrum, rep(.02, 4L))
  expect_error(ugdm_score_covariance(list(A, B), regularization = "eigen"), "Specify")
  expect_error(ugdm_score_covariance(list(A, B), regularization = "diagonal"), "alpha")
  diag <- ugdm_score_covariance(list(A, B), regularization = "diagonal", alpha = 1)
  expect_equal(diag$covariance, diag(diag(raw$average)))
  group <- c("spread", "position", "spread", "position")
  block <- ugdm_score_covariance(list(A, B), regularization = "block", blocks = group, alpha = 1)
  expect_equal(block$covariance, raw$average * outer(group, group, "=="))
  automatic <- ugdm_score_covariance(list(A, B, A + B), regularization = "block", blocks = group)
  expect_gte(automatic$alpha, 0)
  expect_lte(automatic$alpha, 1)
})
